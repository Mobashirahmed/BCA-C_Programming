/* Program to see Data Types in C */
#include<stdio.h>
int main()
{
    int roll = 265074;
    char section = 'B';
    float percentage = 82.6;
    double pi_value = 3.141592653589;

    printf("Roll        :%d\n",roll);
    printf("Section     :%c\n",section);
    printf("Percent     :%f\n",percentage);
    printf("Pi Value    :%lf\n",pi_value);
    return 0;
}